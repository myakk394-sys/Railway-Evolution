package com.fizzylovely.railwayevolution.ai.state;

/**
 * TrainStateId — идентификаторы состояний State Machine.
 *
 * Используется вместо enum TrainState для разделения ID (легковесный)
 * и реализации (TrainControlState). Позволяет добавлять новые состояния
 * без изменения перечисления.
 *
 * Copyright (c) 2026 Fizzy. Licensed under the MIT License.
 */
public enum TrainStateId {

    /** Нормальное движение по маршруту. */
    CRUISING,

    /** Анализ препятствия: замедление, оценка ситуации. */
    ANALYZING_OBSTACLE,

    /**
     * Следование в потоке за другим поездом (AI или игрок).
     * Держим безопасную дистанцию, не останавливаемся полностью.
     */
    FLOW_FOLLOWER,

    /** Уступка дороги: полная остановка, ожидание прохода приоритетного поезда. */
    YIELDING,

    /** Буферный стоп: препятствие в критической зоне, ждём очистки. */
    WAIT_FOR_CLEARANCE,

    /** Реверсный манёвр: откат назад для разблокировки тупика. */
    REVERSING,

    /** Пробка: зажаты спереди и сзади, ждём разрешения. */
    TRAFFIC_JAM,

    /**
     * Управление игрока: AI полностью уступает контроль.
     * SafetyManager продолжает следить за экстремальными ситуациями.
     */
    PLAYER_OVERRIDE
}
